@pytest.mark.parametrize("app,site_name,base", APPS)
def test_contract_102_archived_guides_link_the_archived_reference(app, site_name, base, request):
    """CONTRACT-102: an archived guide's API links stay in the archive and answer 200; no link falls back to the current reference."""
    site = request.getfixturevalue(site_name)
    page = f"{base}/v/1/legacy/alerts".replace("//", "/") if app == "showcase-a" else "/v/1/guides/legacy-client"
    if app == "showcase-a":
        page = "/docs/v/1/legacy/alerts"
    html = site.get(page)[2].decode()
    links = set(re.findall(r'href="([^"]*/reference/generated/[a-z0-9-]+)"', html))
    archived = {link for link in links if "/v/1/" in link}
    assert archived, links
    for link in archived:
        assert site.get(link)[0] == 200, link
    in_content = re.search(r'<analog-markdown.*?</analog-markdown>', html, re.S)
    assert in_content and "/v/1/reference/generated/" in in_content.group(0)
    assert not re.findall(r'href="(?!/(docs/)?v/1/)[^"]*/reference/generated/[^"]*"', in_content.group(0))


def test_contract_103_pagefind_indexes_authored_guides_at_their_canonical_routes(site_a, site_b, site_official):
    """CONTRACT-103: the guides generated from authored pages are in the search index; fragments and the manifest are not."""
    expected = [
        (site_a, "/docs/guides/source-backed-examples", "Source-backed examples"),
        (site_b, "/guides/sdk/quickstart", "SDK quickstart"),
        (site_official, "/docs/guides/content-authoring", "Content authoring"),
        (site_official, "/docs/operations/content-tooling", "Content tooling"),
    ]
    for site, url, title in expected:
        pages = _fragments(site)
        found = [page for page in pages if page["url"].rstrip("/") == url]
        assert found, f"{url} is not indexed"
        assert found[0]["meta"]["title"].startswith(title)
        assert not any("_partials" in page["url"] or "doq-content.json" in page["url"] for page in pages)
    # The playground chrome next to a source example stays out of the index (0.9 policy), the prose stays in.
    guide = next(page for page in _fragments(site_a) if page["url"].rstrip("/") == "/docs/guides/source-backed-examples")
    assert "Change the source and regenerate" in guide["content"] and "Event inspector" not in guide["content"]


def test_contract_104_no_node_only_authoring_code_reaches_a_browser_bundle(site_a, site_b, site_official, package_files):
    """CONTRACT-104: the processor, its manifest handling and file readers are in no client bundle and not in the Angular entry."""
