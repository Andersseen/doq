def _snapshot(root: Path) -> dict[str, str]:
    return {str(path.relative_to(root)): _sha(path) for path in sorted(root.rglob("*")) if path.is_file()}


def test_contract_106_packed_cli_detects_stale_output_without_writing(packed_doq, project):
    """CONTRACT-106: the packed CLI says up to date, then stale (exit 1) after a source change, writing nothing; generate repairs it."""
    ok = _doq(packed_doq, "check", cwd=project)
    assert ok.returncode == 0, ok.stdout + ok.stderr
    source = project / "forge-sdk/src/config.ts"
    source.write_text(source.read_text().replace("// #region doqs:forge-config\n", "// #region doqs:forge-config\n// Changed after generation.\n"))
    before = _snapshot(project)
    stale = _doq(packed_doq, "check", cwd=project)
    assert stale.returncode == 1 and "stale" in stale.stdout and "modified" in stale.stdout
    assert _snapshot(project) == before, "check wrote files"
    assert _doq(packed_doq, "generate", cwd=project).returncode == 0
    assert "Changed after generation." in (project / "src/content/docs/guides/sdk/quickstart.md").read_text()
    assert _doq(packed_doq, "check", cwd=project).returncode == 0
    again = _snapshot(project)
    assert _doq(packed_doq, "generate", cwd=project).returncode == 0
    assert _snapshot(project) == again, "an unchanged project produced different bytes"


@pytest.mark.parametrize(
    "line,code,needle",
    [
        ('::source{file="forge-sdk/src/none.ts"}', 4, "does not exist"),
        ('::source{file="forge-sdk/src/config.ts" region="nope"}', 4, "Available regions: forge-config"),
        ('::source{file="../../../../etc/hosts"}', 4, "outside"),
        ('::source{file="forge-sdk/src/public-api.ts" lines="1-2"}', 0, ""),
        ('::source{file="package.json"}', 4, "outside the configured source roots"),
        ('::include{file="/guides/sdk/quickstart.md"}', 4, "is a page, not a fragment"),
        ("[[api:DefinitelyNotExported]]", 4, "is not a public symbol"),
        ("[[api:ForgeConfig@v9]]", 4, 'no API reference index is configured for "v9"'),
    ],
)
def test_contract_107_invalid_or_unsafe_authoring_fails_with_a_located_diagnostic_and_writes_nothing(packed_doq, project, line, code, needle):
    """CONTRACT-107: broken, unsafe, unknown and ambiguous references exit 4 naming page and line; nothing is written."""
    page = project / "src/authoring/docs/guides/sdk/errors.md"
    page.write_text(page.read_text() + f"\n{line}\n")
    before = _snapshot(project / "src/content")
    result = _doq(packed_doq, "generate", cwd=project)
    if code == 0:
        assert result.returncode == 0, result.stderr
        return
    assert result.returncode == code, result.stdout + result.stderr
    assert "src/authoring/docs/guides/sdk/errors.md:" in result.stderr and needle in result.stderr
    assert _snapshot(project / "src/content") == before
